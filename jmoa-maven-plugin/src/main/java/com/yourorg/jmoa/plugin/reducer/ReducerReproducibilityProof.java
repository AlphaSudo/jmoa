package com.yourorg.jmoa.plugin.reducer;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.Enumeration;
import java.util.HexFormat;
import java.util.List;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/** Two-clean-build proof required before a reproducible-layout verdict. */
public final class ReducerReproducibilityProof {

    public static final List<String> UNSUPPORTED_RAW_ZIP_FIELDS = List.of(
            "extra-field blocks not generated by java.util.zip (vendor-specific id/values)",
            "original entry comment byte sequences when a re-encode differs",
            "data-descriptor presence/absence choice per entry",
            "ZIP64 extra-field sizing and ordering",
            "internal attributes and disk-number padding bits",
            "sub-second precision of entry timestamps");

    public record JarProof(
            String relativePath,
            String buildASha256,
            String buildBSha256,
            String buildAEntryMetadataSha256,
            String buildBEntryMetadataSha256,
            boolean bytesIdentical,
            boolean entryMetadataIdentical) {
    }

    public record ProofRecord(
            String inputTreeSha256,
            String buildARoot,
            String buildBRoot,
            String buildAStartedAtUtc,
            String buildBStartedAtUtc,
            int jarCount,
            int entryCount,
            boolean entryOrderIdentical,
            boolean entryMetadataIdentical,
            List<JarProof> jars,
            List<String> differingEntries,
            boolean allBytesIdentical,
            boolean passed) {
        public ProofRecord {
            jars = List.copyOf(jars);
            differingEntries = List.copyOf(differingEntries);
        }

        /** Compatibility constructor for callers that synthesize verdict fixtures. */
        public ProofRecord(String buildARoot, String buildBRoot, int jarCount, int entryCount,
                boolean entryOrderIdentical, List<String> differingEntries,
                boolean allBytesIdentical, boolean passed) {
            this("UNBOUND_FIXTURE_INPUT", buildARoot, buildBRoot, "UNRECORDED", "UNRECORDED",
                    jarCount, entryCount, entryOrderIdentical, passed, List.of(),
                    differingEntries, allBytesIdentical, passed);
        }
    }

    public static ProofRecord prove(Path inputDir, boolean mutationEnabled, String operation, String jarLayout)
            throws IOException {
        Path scratch = Files.createTempDirectory("reducer-repro-proof");
        try {
            Path buildA = Files.createDirectories(scratch.resolve("build-a"));
            Path buildB = Files.createDirectories(scratch.resolve("build-b"));
            String startedA = Instant.now().toString();
            ReducerReport reportA = new JarReducer(config(inputDir, buildA, mutationEnabled, operation, jarLayout)).reduce();
            try {
                Thread.sleep(20);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                throw new IOException("reproducibility proof interrupted", e);
            }
            String startedB = Instant.now().toString();
            ReducerReport reportB = new JarReducer(config(inputDir, buildB, mutationEnabled, operation, jarLayout)).reduce();
            if (reportA == null || reportB == null) {
                throw new IOException("reproducibility proof builds failed");
            }
            return compare(inputTreeSha256(inputDir), buildA, buildB, startedA, startedB);
        } finally {
            try (Stream<Path> paths = Files.walk(scratch)) {
                paths.sorted(Comparator.reverseOrder()).forEach(path -> path.toFile().delete());
            }
        }
    }

    static ProofRecord compare(Path buildA, Path buildB) throws IOException {
        return compare("UNBOUND_TEST_INPUT", buildA, buildB, "UNRECORDED", "UNRECORDED");
    }

    private static ProofRecord compare(String inputHash, Path buildA, Path buildB,
            String startedA, String startedB) throws IOException {
        List<Path> jarsA = sortedJars(buildA);
        List<Path> jarsB = sortedJars(buildB);
        List<String> differences = new ArrayList<>();
        List<JarProof> proofs = new ArrayList<>();
        boolean orderIdentical = jarsA.size() == jarsB.size();
        boolean metadataIdentical = jarsA.size() == jarsB.size();
        boolean allBytes = jarsA.size() == jarsB.size();
        int entryCount = 0;
        if (jarsA.size() != jarsB.size()) {
            differences.add("jar count differs: " + jarsA.size() + " vs " + jarsB.size());
        }
        for (int i = 0; i < Math.min(jarsA.size(), jarsB.size()); i++) {
            Path jarA = jarsA.get(i);
            Path jarB = jarsB.get(i);
            String relativeA = buildA.relativize(jarA).toString().replace('\\', '/');
            String relativeB = buildB.relativize(jarB).toString().replace('\\', '/');
            if (!relativeA.equals(relativeB)) {
                orderIdentical = false;
                differences.add("jar path/order differs at " + i + ": " + relativeA + " vs " + relativeB);
            }
            String shaA = sha256(jarA);
            String shaB = sha256(jarB);
            boolean bytesEqual = shaA.equals(shaB);
            if (!bytesEqual) {
                allBytes = false;
                differences.add("jar bytes differ: " + relativeA);
            }
            EntryComparison entryComparison = compareEntries(jarA, jarB, differences);
            entryCount += entryComparison.count();
            metadataIdentical &= entryComparison.metadataIdentical();
            proofs.add(new JarProof(relativeA, shaA, shaB,
                    entryComparison.leftMetadataHash(), entryComparison.rightMetadataHash(),
                    bytesEqual, entryComparison.metadataIdentical()));
        }
        boolean distinctRoots = !buildA.toAbsolutePath().normalize().equals(buildB.toAbsolutePath().normalize());
        boolean passed = distinctRoots && entryCount > 0 && orderIdentical && metadataIdentical
                && allBytes && differences.isEmpty();
        return new ProofRecord(inputHash, buildA.toAbsolutePath().toString(), buildB.toAbsolutePath().toString(),
                startedA, startedB, jarsA.size(), entryCount, orderIdentical, metadataIdentical,
                proofs, differences, allBytes, passed);
    }

    private record EntryComparison(int count, boolean metadataIdentical,
            String leftMetadataHash, String rightMetadataHash) {
    }

    private static EntryComparison compareEntries(Path jarA, Path jarB, List<String> differences) throws IOException {
        try (ZipFile left = new ZipFile(jarA.toFile()); ZipFile right = new ZipFile(jarB.toFile())) {
            List<String> leftNames = entryNames(left);
            List<String> rightNames = entryNames(right);
            if (!leftNames.equals(rightNames)) {
                differences.add("entry order/set differs in " + jarA.getFileName());
            }
            for (String name : leftNames) {
                ZipEntry a = left.getEntry(name);
                ZipEntry b = right.getEntry(name);
                if (b == null) {
                    differences.add("entry missing in build B: " + name);
                } else if (a.getCrc() != b.getCrc() || a.getSize() != b.getSize()) {
                    differences.add("entry crc/size differs: " + name);
                }
            }
            String leftMetadata = metadataHash(left);
            String rightMetadata = metadataHash(right);
            boolean metadataEqual = leftMetadata.equals(rightMetadata);
            if (!metadataEqual) {
                differences.add("entry metadata differs in " + jarA.getFileName());
            }
            return new EntryComparison(leftNames.size(), metadataEqual, leftMetadata, rightMetadata);
        }
    }

    private static List<String> entryNames(ZipFile zip) {
        List<String> names = new ArrayList<>();
        Enumeration<? extends ZipEntry> entries = zip.entries();
        while (entries.hasMoreElements()) names.add(entries.nextElement().getName());
        return names;
    }

    private static String metadataHash(ZipFile zip) throws IOException {
        StringBuilder value = new StringBuilder();
        Enumeration<? extends ZipEntry> entries = zip.entries();
        while (entries.hasMoreElements()) {
            ZipEntry entry = entries.nextElement();
            value.append(entry.getName()).append('|').append(entry.getMethod()).append('|')
                    .append(entry.getSize()).append('|').append(entry.getCompressedSize()).append('|')
                    .append(entry.getCrc()).append('|').append(entry.getTime()).append('|')
                    .append(entry.getComment() == null ? "" : entry.getComment()).append('|');
            byte[] extra = entry.getExtra();
            value.append(extra == null ? "" : sha256(extra)).append('\n');
        }
        return sha256(value.toString().getBytes(StandardCharsets.UTF_8));
    }

    private static List<Path> sortedJars(Path root) throws IOException {
        try (Stream<Path> paths = Files.walk(root)) {
            return paths.filter(path -> path.toString().endsWith(".jar")).sorted().toList();
        }
    }

    private static String inputTreeSha256(Path root) throws IOException {
        StringBuilder value = new StringBuilder();
        for (Path jar : sortedJars(root)) {
            value.append(root.toAbsolutePath().normalize().relativize(jar.toAbsolutePath().normalize()))
                    .append('|').append(sha256(jar)).append('\n');
        }
        return sha256(value.toString().getBytes(StandardCharsets.UTF_8));
    }

    private static String sha256(Path file) throws IOException { return sha256(Files.readAllBytes(file)); }

    private static String sha256(byte[] bytes) throws IOException {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)).toUpperCase();
        } catch (Exception e) {
            throw new IOException("SHA-256 unavailable", e);
        }
    }

    private static ReducerConfig config(Path input, Path output, boolean mutationEnabled,
            String operation, String jarLayout) {
        return new ReducerConfig(false, mutationEnabled, "release-low-footprint", input.toFile(), output.toFile(),
                false, false, false, false, false, false, false, false,
                "raw", false, null, "report-only", "", "", operation, jarLayout);
    }

    private ReducerReproducibilityProof() {
    }
}
